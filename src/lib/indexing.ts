/**
 * 検索エンジンに載せるかどうか。
 *
 * ## お客様向けの画面は、載せます（2026-11-10 に公開）
 *
 * 公開前は全ページに noindex を付け、環境変数で開ける作りにしていました。
 * 公開したので、その仕組みごと外しました。**載せ続けるために環境変数が
 * 要る**という形にしておくと、いつか変数が外れた日に黙って検索結果から
 * 消えます。気づくきっかけがどこにもありません。
 *
 * また載せたくなくなったら、`src/app/layout.tsx` の metadata に
 * `robots: NOINDEX` を足してください。
 *
 * ## 管理画面は、ずっと載せません
 *
 * `src/app/admin/layout.tsx` が上書きしています。入られれば予約全部の
 * 氏名・メール・電話が見えるところなので、公開とは関係なく外します。
 *
 * ## robots.txt では止めません
 *
 * robots.txt で蹴ると、クローラはページを**読みに来ません**。読みに来ない
 * ということは、ページに書いた「載せないで」という指示も読まれません。
 * その結果、どこかから貼られたリンク経由で URL だけが検索結果に出る、
 * ということが起こりえます。
 *
 * 載せないでほしいときは、**読ませたうえで noindex を伝える**のが正しい
 * やり方です。だから robots.txt は通しておきます（管理画面と API だけは、
 * 読みに来てもらう理由が無いので外しています）。
 */
/** 載せたくないページに付ける指示。いまは管理画面だけが使います。 */
export const NOINDEX = {
  index: false,
  follow: false,
  nocache: true,
  googleBot: { index: false, follow: false },
} as const;
